from pathlib import Path

import numpy as np
from PIL import Image


def plot_waveform_for_image_decode(signal, image_path="waveform_for_decode.png"):
    """Save a clean, calibrated waveform image for pixel-based decoding."""
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    signal = np.asarray(signal, dtype=float)
    if signal.size == 0:
        raise ValueError("Signal cannot be empty.")
    if not np.all(np.isin(signal, [-1, 0, 1])):
        raise ValueError("Image decoder currently supports levels -1, 0, and +1.")

    fig, ax = plt.subplots(
        figsize=(max(8, len(signal) * 0.35), 3),
        dpi=150,
    )
    ax.step(
        np.arange(len(signal)),
        signal,
        where="post",
        color="black",
        linewidth=2.5,
    )
    ax.set_xlim(0, len(signal))
    # Fixed calibration makes level position interpretable from pixels alone.
    ax.set_ylim(-1.5, 1.5)
    ax.axis("off")
    fig.subplots_adjust(left=0.02, right=0.98, top=0.95, bottom=0.05)
    fig.savefig(
        image_path,
        facecolor="white",
        bbox_inches="tight",
        pad_inches=0.08,
    )
    plt.close(fig)
    return str(image_path)


def decode_waveform_image(image_path, expected_levels):
    """
    Recover -1/0/+1 signal levels by sampling waveform pixels.

    This is intended for clean images produced by
    plot_waveform_for_image_decode(). expected_levels is the number of
    plotted signal intervals. It is not designed for arbitrary screenshots.
    """
    if expected_levels <= 0:
        raise ValueError("expected_levels must be positive.")

    image = Image.open(image_path).convert("RGB")
    pixels = np.asarray(image)
    height, width, _ = pixels.shape
    dark = pixels.mean(axis=2) < 100

    left = max(0, int(width * 0.02))
    right = min(width, int(width * 0.98))
    usable_width = right - left
    if usable_width < expected_levels:
        raise ValueError("Image is too narrow for the requested signal length.")

    recovered = []
    for i in range(expected_levels):
        x = left + int((i + 0.5) * usable_width / expected_levels)
        x = min(x, width - 1)
        ys = np.flatnonzero(dark[:, x])

        if len(ys) == 0:
            x0 = max(left, x - 2)
            x1 = min(right, x + 3)
            ys = np.flatnonzero(dark[:, x0:x1].any(axis=1))

        if len(ys) == 0:
            raise ValueError(
                f"No waveform pixels found at interval {i}. "
                "Use the clean image generated by this module."
            )

        y_fraction = float(np.median(ys)) / max(1, height - 1)

        # Fixed plot limits: +1 is near the top, 0 near the middle,
        # and -1 near the bottom of the image.
        if y_fraction < 0.35:
            recovered.append(1)
        elif y_fraction > 0.65:
            recovered.append(-1)
        else:
            recovered.append(0)

    return recovered
